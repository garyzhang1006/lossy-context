def brute_marginal(P, delta, kernel=POWER):
    """Definition-level mixture, written out with a Python loop on purpose."""
    K = P.shape[0] - 1
    out = np.zeros(P.shape[1])
    for j in range(K + 1):
        r_j = 1.0 if j == 0 else float(kernel(np.array([j]), delta)[0])
        r_j1 = 0.0 if j == K else float(kernel(np.array([j + 1]), delta)[0])
        out += (r_j - r_j1) * P[j]
    return out


